export const textWidth = (text, scale) => text.length * 4 * scale - scale;

/** dst 에 text 를 (x,y) 부터 그린다. setPixel = (x,y)=>void 콜백. */
export function drawText(text, x, y, scale, setPixel) {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = FONT[ch];
    if (g) {
      for (let r = 0; r < 5; r++)
        for (let c = 0; c < 3; c++)
          if (g[r][c] === '1')
            for (let dy = 0; dy < scale; dy++)
              for (let dx = 0; dx < scale; dx++) setPixel(cx + c * scale + dx, y + r * scale + dy);
    }
    cx += 4 * scale;
  }
}
