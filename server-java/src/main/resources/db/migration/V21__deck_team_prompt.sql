-- #253 — 덱 화면 "팀 전체 프롬프트"가 저장되지 않던 데이터 유실의 저장소 쪽 픽스.
--
-- 증상: 유저가 덱 화면에서 팀 문장을 쓰고 [저장]을 눌러도 PUT /api/deck 바디에 담길 자리가 없어
-- 화면만 "저장되었습니다"를 띄우고 리로드하면 사라졌다. **선수별** 문장은 deck_slots.prompt_text 로
-- 정상 저장되므로 유저 눈에는 "선수 문장은 남는데 팀 문장만 없어진다"로 보여 더 헷갈렸다(#244 검증 Minor-8).
--
-- 왜 덱에 두는가(#253 산출물 1 의 결정): 팀 문장은 **선수 문장과 같은 성격의 덱 사전 지시**다.
-- 선수 문장이 deck_slots 에 있으니 팀 문장은 decks 에 있는 게 대칭이고, 그래야
--   ① 덱 스냅샷(user_deck_json) 직렬화 한 곳(DeckSnapshot)이 팀·선수 문장을 함께 싣고
--   ② 그 스냅샷으로 만드는 A(베이스) 캐시 키에 팀 문장이 **자동으로** 들어간다(#215 정합 — 문장이
--      바뀌면 baseId 가 바뀌어 재생성, 안 바뀌면 그대로 캐시 히트).
-- 별도 리소스(/api/prompts 계열)로 두면 저장 시점 선실행이 두 리소스를 조합해야 해서 위 ②가 깨진다.
--
-- 매치 시점의 팀 문장(match_prompts phase=pre|halftime)과의 관계: **덱 문장이 기본값이고 매치가
-- 덮어쓴다**(PromptContextBuilder.userPromptSet — 덱 ← pre ← halftime). 여기 없으면 종전과 같이 "".
--
-- NULL 허용 = 기존 덱은 팀 문장 없음. DeckSnapshot 은 null/공백이면 필드를 **생략**하므로 기존 덱의
-- 스냅샷 바이트가 그대로 유지된다 → 라이브에 쌓인 A 캐시가 이 마이그레이션으로 무효화되지 않는다.
