-- #245 후속 (hero 리뷰 2026-07-29): **A-1 몰수 격리**.
--
-- 시즌 화면(B)은 이 리뷰에서 승인되지 않았다 — 그쪽 컬럼은 착수할 때 별도 마이그레이션으로 넣는다.

-- ── A-1: 몰수 표식 ──────────────────────────────────────────────────────────
-- 왜 컬럼인가: 지금까지 몰수는 "0:0 인데 무승부가 아님"으로 **역추론**했다(정상 경기의 0:0 은 언제나
-- DRAW 라 그 조합이 몰수에서만 나온다). 화면 라벨 하나엔 그걸로 충분했지만, 이제 **시즌 참가·연승
-- 판정**이 여기에 걸린다 — 규칙이 하나 늘면(예: 무득점 몰수 아닌 결과) 조용히 오분류된다.
-- 판정에 쓸 사실은 파생하지 말고 박아 둔다.
--
-- 왜 격리하나: 몰수는 **경기가 열리지도 않은 것**이다. 그런데 리포트가 남으므로 시즌 참가로 잡히고
-- 연승도 쌓였다 → 두 계정이 서로 만들고 무르기만 해도 **시뮬 0회·AI 0회로** 주간 순위 보상(1위 30k +
-- 2위 20k)을 가져가는 경로가 됐다. 레이팅은 서로 상쇄돼 밴드 매칭 방어도 걸리지 않는다.
-- 레이팅 ±10 은 그대로 준다 — 그게 무르는 쪽에 대한 벌칙이고 hero D1 이다.
ALTER TABLE away_reports ADD COLUMN forfeit INTEGER NOT NULL DEFAULT 0;

-- 기존 행 백필: 그동안의 몰수 = 0:0 + 비무승부(위 역추론 규칙). 이 시점 이후로는 컬럼이 정본이다.
UPDATE away_reports SET forfeit = 1
WHERE goals_for = 0 AND goals_against = 0 AND result <> 'DRAW';

-- 시즌 마감이 매주 훑는 조건이라 인덱스를 둔다(참가자 = 창 안의 비-몰수 리포트).
CREATE INDEX idx_away_reports_season ON away_reports(created_at, forfeit);
