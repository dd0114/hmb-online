-- #207 blocker B1 — unit_create 멱등의 **DB 백스톱**.
-- additive only — V14 은 손대지 않는다(체크섬 불변). 여기서 인덱스 하나를 **추가**할 뿐이다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 무엇이 깨져 있었나
-- ─────────────────────────────────────────────────────────────────────────────
-- V14 의 uq_catalog_audit_idem(action, player_id, idem_key) 는 **대상별** 스코프다. 대상이
-- 이미 존재하는 액션(update/deactivate/activate/override_reset)에는 정확한 백스톱이지만,
-- unit_create 에는 **아무 제약도 아니다** — 생성은 id 를 서버가 채번하므로 같은 키로 재전송할
-- 때마다 player_id 가 달라진다(P182 ≠ P183). 즉 (unit_create, P182, K) 와 (unit_create, P183, K)
-- 는 서로 다른 키라 인덱스가 통과시킨다.
--
-- 그래서 생성 경로의 멱등은 **앱 레벨 사전조회(AdminCatalogService.findAudit) 하나에만** 의존했고,
-- 그건 check-then-act 라 경합을 막지 못한다. 독립 검증자 실측(신규 DB, 같은 Idempotency-Key 로
-- POST /api/admin/units 10발 동시):
--     HTTP 200, 200, 500 x8 · players 에 유닛 2개(P182·P183) · 감사에 같은 키 2행
-- 그리고 더 나쁜 후유증 — 그 뒤 **순차** 요청도 영구 500 이었다. 사전조회가 단일행을 가정하는데
-- (`.optional()`) 그 키에 2행이 있어 IncorrectResultSizeDataAccessException 이 터졌다.
-- 즉 한 번의 경합이 그 멱등키를 **영구히 사용 불가**로 만들었다.
--
-- 이 리포의 원칙은 fail-closed 다: 앱이 먼저 거르되, **진실은 DB 제약이 지킨다**. 생성 경로만
-- 그 원칙에서 빠져 있었다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 1) 선행 오염 정리 — 왜 삭제가 아니라 "멱등키 회수"인가
-- ─────────────────────────────────────────────────────────────────────────────
-- 유니크 인덱스 생성은 **기존 중복이 한 쌍이라도 있으면 실패**한다. 그리고 실패한 마이그레이션은
-- 부팅을 죽인다 — 이미 경합을 겪은 DB(검증자 재현 DB 가 정확히 그 상태다)는 이 마이그레이션을
-- 그냥 얹으면 **기동 불가**가 된다. 그래서 인덱스보다 먼저 정리한다.
--
-- 정리 방식으로 중복 감사행 **삭제**는 택하지 않았다. 그 행들은 "실패한 요청의 찌꺼기"가 아니라
-- **실제로 일어난 생성의 유일한 증거**다 — 중복 생성된 유닛(P183)은 players 에 남아 있고, 감사행을
-- 지우면 그 유닛은 **누가 언제 왜 만들었는지 알 수 없는 고아**가 된다. 감사 원장에서 이력을 지우는
-- 것은 이 테이블의 존재 이유(§V14 "이력의 SoT")와 정면으로 충돌한다.
--
-- 대신 **멱등키만 회수**한다: 같은 (unit_create, idem_key) 그룹에서 (created_at, id) 최소 = 최초
-- 성공분 한 행만 키를 유지하고, 나머지는 idem_key 를 NULL 로 내린다(부분 인덱스가 NULL 을 세지
-- 않으므로 유니크가 성립한다). 회수된 키 문자열은 **버리지 않고 reason 에 각인**한다 — 운영자가
-- "이 키로 뭐가 더 만들어졌나"를 나중에도 검색할 수 있어야 하기 때문이다(회수 사실 자체도 이력이다).
--
-- 최초 성공분을 승자로 고르는 이유: 앱의 재전송 재생(replay)이 돌려주는 유닛과 일치해야 한다.
-- AdminCatalogService.findAudit 도 같은 정렬(created_at, id)로 한 행을 집으므로 **DB 정리와 앱
-- 조회가 같은 행을 가리킨다**(둘이 어긋나면 정리 후에도 재생 결과가 흔들린다).
--
-- 정상 DB(중복 0)에서는 이 UPDATE 가 0행을 건드린다 = 무회귀.
UPDATE admin_catalog_audit
   SET reason   = reason || ' [V15: 동시 생성 경합으로 중복된 멱등키 회수 — 원 키=' || idem_key || ']',
       idem_key = NULL
 WHERE action = 'unit_create'
   AND idem_key IS NOT NULL
   AND id <> (SELECT w.id
                FROM admin_catalog_audit w
               WHERE w.action = 'unit_create'
                 AND w.idem_key = admin_catalog_audit.idem_key
               ORDER BY w.created_at, w.id
               LIMIT 1);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2) 백스톱 인덱스 — unit_create 만 (action, idem_key) 전역 스코프
-- ─────────────────────────────────────────────────────────────────────────────
-- **부분** 인덱스인 것이 핵심이다. V5 가 감사 멱등을 전역 (action, idem_key) 로 잡았다가 서로 다른
-- 대상에 같은 키가 오면 UNIQUE 로 터져 V6 로 되돌린 실패가 있었다(V14 주석 참조). 그 교훈은 유효하다 —
-- 다만 그 실패는 **대상이 존재하는 액션**의 이야기다. unit_create 는 대상이 아직 없으므로 "서로 다른
-- 대상에 같은 키"라는 정상 시나리오 자체가 성립하지 않는다: 같은 키의 두 create 는 정의상 **같은
-- 요청의 재전송**이다. 그래서 이 액션에서만 전역 스코프가 옳고, WHERE 절로 딱 거기만 잠근다.
-- (다른 4개 액션의 동작은 한 바이트도 바뀌지 않는다 — V14 인덱스가 그대로 담당한다.)
--
-- idem_key IS NOT NULL 조건: 헤더 없이 온 요청은 서버가 ULID 를 채번하므로 실제로 NULL 이 들어오는
-- 경로는 지금 없지만, 스키마가 NULL 을 허용하고 위 정리 UPDATE 가 NULL 을 만들므로 명시한다.
--
-- 컬럼에 action 을 함께 넣은 이유(WHERE 로 이미 고정돼 중복처럼 보이지만): 앱의 조회가
-- `WHERE action = ? AND idem_key = ?` 라 이 인덱스가 **그 조회의 커버링 인덱스**로도 쓰인다.
CREATE UNIQUE INDEX uq_catalog_audit_create_idem
  ON admin_catalog_audit(action, idem_key)
  WHERE action = 'unit_create' AND idem_key IS NOT NULL;
