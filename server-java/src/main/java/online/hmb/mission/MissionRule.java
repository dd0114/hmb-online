package online.hmb.mission;

/**
 * 미션 판정 규칙 (#408 §4) — 원정 경기 한 판의 결과가 진행도를 어떻게 미는가.
 *
 * <p><b>규칙은 두 종류뿐이다</b>: 하루 동안 <b>세는 것</b>(COUNT 계열)과 한 경기의 <b>최고값</b>을
 * 기억하는 것(BEST 계열). 미션 14종이 이 일곱 갈래로 전부 표현된다 — 미션마다 분기를 쓰면
 * 카탈로그를 늘릴 때마다 판정 코드를 고쳐야 하고, 그때 이미 발급된 행의 판정이 바뀐다.
 *
 * <p>⚠️ 이 이름은 {@code daily_missions.rule} 에 <b>박제</b>된다. 값을 개명하면 그날 진행 중인
 * 행이 판정 불가가 된다 — 개명이 필요하면 새 값을 추가하고 카탈로그만 옮겨라.
 */
public enum MissionRule {

    /** 완료된 원정 경기 수. 승패·득점과 무관 — 포기는 정산 경로를 지나지 않으므로 애초에 안 센다. */
    PLAY,

    /** 하루 누적 승수. */
    WIN,

    /**
     * 하루 안의 <b>연속</b> 승수. 승 +1 · 패 0 으로 끊김 · <b>무승부는 유지</b>.
     *
     * <p>무승부 유지는 {@code AwayService} 의 통산 연승(hero E4)과 같은 규칙이다 — 두 화면이 서로
     * 다른 "연승"을 말하면 유저는 어느 쪽도 믿지 않는다. 하루 경계는 미션 행이 day 로 잘려 있어
     * 자동으로 성립한다({@code away_streaks} 는 통산이라 그대로 쓸 수 없다).
     */
    WIN_STREAK,

    /** 한 경기 최다 득점(하루 최고값). 합계가 아니다 — "한 경기에서 N골"이 요구다. */
    BEST_MATCH_GOALS,

    /** 무실점 승리 횟수({@code WIN && oppGoals == 0}). */
    CLEAN_WIN,

    /** 승리한 경기의 최대 골 차(하루 최고값). 진 경기는 0 으로 본다. */
    BEST_WIN_MARGIN,

    /** 선제골을 넣은 경기 수 — 매치로그의 <b>첫 goal 이벤트</b>가 우리 팀인 경기. */
    FIRST_GOAL
}
