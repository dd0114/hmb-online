/**
 * 시드 RNG로 유일한 성명을 하나 뽑는다. 이미 사용됐거나 실선수 거부 목록에 있으면
 * 재시도(결정론적 — 동일 RNG 시퀀스·동일 정적 목록에서 항상 동일한 결과).
 */
export function nextUniqueName(
  rng: { nextInt(n: number): number },
  used: Set<string>,
): string {
  // 조합 공간(11,440)이 필요 수량(110)+거부 목록보다 훨씬 커서 무한루프 위험은 없다.
  for (let attempt = 0; attempt < 100000; attempt++) {
    const surname = SURNAMES[rng.nextInt(SURNAMES.length)];
    const g1 = GIVEN1[rng.nextInt(GIVEN1.length)];
    const g2 = GIVEN2[rng.nextInt(GIVEN2.length)];
    const name = `${surname}${g1}${g2}`;
    if (!used.has(name) && !DENY.has(name)) {
      used.add(name);
      return name;
    }
  }
  throw new Error("nextUniqueName: 조합 공간 소진 — 풀을 늘려야 함");
}
