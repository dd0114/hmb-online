/**
 * 팀 사이드 색 — **단일 출처**(#456 B4).
 *
 * hero 요구는 *"경기 스킵 이후 결과 보여줄 때 어느 팀인지 색구분해서 보여줘"* 였고, 그걸 넣으려
 * 보니 팀색이 이미 **네 파일에 리터럴로 흩어져** 있었다(스코어바 · 통계 패널 · 하프 리포트 주요
 * 인물 원 · 타임라인 핀). 그 상태에서 리포트에 색을 하나 더 적으면 다섯 번째 출처가 된다.
 *
 * ## 역할이 셋이라 값도 셋이다 — 합치지 마라(합치려면 그건 **시각 결정**이다)
 *
 * | 역할 | 어디 | 왜 값이 다른가 |
 * |---|---|---|
 * | `text` | 스코어바 이름 · 통계 점유율·팀 슬롯 · **리포트 행 팀 라벨** | 어두운 배경 위 **글자**라 밝고 옅다 |
 * | `strong` | 스크럽 바 골 핀 · 통계 막대 · 선수 번호 원 · 선택 카드 원 | 작은 마크·채운 면이라 **진해야** 보인다 |
 * | `soft` | 주요 인물 등번호 원(배경) | 큰 원 위에 **어두운 글자**가 앉아 밝아야 대비가 산다 |
 *
 * ⚠️ **`soft` 는 소비처가 하나뿐이다**(하프 리포트 주요 인물 원). 즉 이 표에서 가장 합칠 만한
 * 후보이고, 합치면 그 원의 배경이 `#6ab7ff → #3b82f6` 으로 진해진다 = **그 화면 하나가 대가**다.
 * 값을 바꾸려면 그걸 알고 바꿔라(이 웨이브는 바꾸지 않았다).
 *
 * ⚠️ **이 웨이브는 값을 하나도 안 바꿨다.** 토큰화는 *"출처를 하나로"* 이고 *"세 값을 한 값으로"* 는
 * 화면 다섯 개가 같이 바뀌는 별개의 결정이다(hero 눈 판정 대상) — 섞으면 리팩터에 시각 변경이
 * 몰래 올라탄다. 통일하고 싶으면 이 표의 두 줄을 지우면 되고, 그때 바뀌는 화면이 곧 그 대가다.
 *
 * ## CSS 와 TS 두 벌인 이유, 그리고 그 둘이 갈라지지 않는 방법
 *
 * `timeline-pins.ts` 는 **TS 가 색 문자열을 만들어 인라인 스타일로 넘긴다** — CSS 변수 선언만으로는
 * 못 덮는다. 그래서 `index.css :root` 의 `--team-*` 와 이 상수가 **쌍**으로 존재하고,
 * `team-colors.test.ts` 가 두 벌이 같은 값인지를 계약으로 잡는다(드리프트 = red).
 */
export type TeamSide = "home" | "away";

export const TEAM_COLORS: Record<TeamSide, { text: string; strong: string; soft: string }> = {
  home: { text: "#7ab0ff", strong: "#3b82f6", soft: "#6ab7ff" },
  away: { text: "#ff8f8f", strong: "#ef4444", soft: "#ff8a7a" },
};

/** `index.css` 에 선언된 CSS 변수 이름 — 계약이 이 목록을 그대로 훑는다. */
export function teamColorVar(side: TeamSide, role: "text" | "strong" | "soft"): string {
  return `--team-${side}-${role}`;
}
