/**
 * 공지 본문의 이미지·링크 경로를 **지금 백엔드 오리진**으로 해석한다 (#309 W1).
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 왜 이 파일이 있나 — 공지 이미지가 서버에 저장되기 시작했기 때문이다.
 *
 * 업로드한 이미지는 본문에 **상대경로**(`/api/notices/assets/{id}`)로 적힌다. 절대 URL 을 적으면
 * 안 되는 이유가 이 설계의 핵심이다: 백엔드는 quick tunnel 뒤에 있어 **주소가 죽을 때마다 바뀐다**
 * (실적 있음). 절대 URL 을 본문에 구우면 터널이 한 번 죽는 순간 **과거 공지 이미지가 전부 깨지고**
 * 복구가 본문 일괄 수정뿐이다.
 *
 * 그런데 web 은 CF Pages(정적)에 있어 `/api/...` 를 받아 줄 서버가 **그 오리진에 없다**. 그래서
 * 렌더 시점에 현재 백엔드 오리진을 붙인다 — 자가복구 워치독(#183)이 갱신한 주소를 그냥 따라간다.
 *
 * ⚠️ **`/api/` 로 시작하는 것만 옮긴다.** 기존 정적 에셋(`/notice/hero-kyeongnicius.webp`)은
 *    **웹 오리진**에 있고 계속 거기 있어야 한다 — 전부 옮기면 그 그림이 백엔드에서 404 가 된다.
 *    이 한 줄이 "공존"(#309 요구)의 전부다.
 * ⚠️ 외부 URL(`https://…`)도 손대지 않는다. 이미 절대 주소이므로 붙일 것이 없다.
 * ════════════════════════════════════════════════════════════════════════════
 */
import { apiUrl } from "../api/client";

/** 서버가 서빙하는 공지 이미지의 경로 접두. 본문에 적히는 형태이자 이 해석의 트리거다. */
export const NOTICE_ASSET_PATH_PREFIX = "/api/notices/assets/";

/**
 * 본문에 적힌 경로 → 실제로 요청할 URL.
 *
 * dev·테스트·데모(8080)에서는 `apiBase()` 가 `""` 라 **항등 함수**다 — 그래서 이걸 넣어도
 * 기존 화면·계약이 한 바이트도 달라지지 않는다.
 */
export function resolveNoticeUrl(src: string): string {
  return src.startsWith("/api/") ? apiUrl(src) : src;
}

/** 업로드한 자산 id → 본문에 붙일 마크업. 운영 UI 와 계약이 같은 문자열을 쓰게 한다. */
export function noticeAssetMarkup(id: string, alt: string = ""): string {
  return `![${alt}](${NOTICE_ASSET_PATH_PREFIX}${id})`;
}
