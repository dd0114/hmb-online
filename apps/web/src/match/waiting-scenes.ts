/**
 * 경기 준비 대기 화면(GEN1/GEN2)의 **축구장 정경 묘사 문구 풀** — #382.
 *
 * ## 왜 이 파일이 있나
 *
 * 예전 대기 화면은 시스템을 설명했다 — *"감독의 지시가 선수들에게 전달되고 있습니다
 * (보통 10초 안팎, 전술을 크게 바꾼 경우 1~2분)"*. 실측과는 맞았지만(#193) hero 가 라이브에서
 * 직접 걷어냈다: *"경기 준비할 때 문구 이렇게 하지 않기로 했잖아. 축구장 상황을 묘사하는
 * 문구로 바꿔. (…) 기다리기 지루하니까."*
 *
 * 그래서 이 자리는 **서버가 무엇을 하고 있는지**를 말하지 않는다. 유저가 서 있는 곳(경기장)에서
 * 지금 무슨 일이 벌어지고 있는지만 그린다. 기다리는 시간이 얼마인지는 **경과 시계**
 * (`genwait-elapsed`)가 이미 말해 준다 — 문장이 그것을 중복해서 예고할 필요가 없다.
 *
 * ## 규칙 (문장을 추가할 때)
 *
 * 1. **현재진행형 정경 묘사**("…고 있습니다"). 상태 보고가 아니라 중계 화면에 비치는 장면이다.
 * 2. **시스템 용어·소요시간 금지** — AI·작전·반영·지시·전달·생성·로딩·서버·초·분·숫자.
 *    계약(`waiting-scenes.test.ts`)이 목록으로 막는다.
 * 3. **전/후반 어느 쪽에서도 성립하는 문장만** 넣는다. 풀을 단계별로 가르지 않았다 —
 *    전반 전용/후반 전용으로 쪼개면 짧은 GEN2(실측 0.3초)에서 절반이 영영 안 보이고,
 *    "입장"·"몸풀기"는 하프타임 뒤에도 실제로 일어나는 장면이다.
 * 4. hero 가 준 4문장(`HERO_SCENE_LINES`)은 **맨 앞에 그대로** 둔다. 대기가 짧으면 앞쪽만
 *    보이므로, hero 가 지정한 장면이 실제로 노출되는 자리가 거기다.
 *
 * ⚠️ hero 원문에서 고친 것은 **맞춤법뿐**이다 — 띄어쓰기("입장하고있습니다" → "입장하고 있습니다")와
 * 조사 1건("선수들에게 격려" → "선수들을 격려", `격려하다` 는 을/를 을 받는다. hero 확정 2026-08-01).
 * 어휘·어순은 원문 그대로다 — 표현을 "다듬는" 것은 hero 의 몫이라 손대지 않는다.
 */

/** hero 가 직접 준 4문장(#382 원문). 순서·표현을 바꾸지 마라 — 계약이 리터럴로 들고 있다. */
export const HERO_SCENE_LINES = [
  "선수들이 입장하고 있습니다",
  "감독이 선수들을 격려하고 있습니다",
  "선수의 신발끈을 다시 묶고 있습니다",
  "파인 잔디를 조금 보수하고 있습니다",
] as const;

/**
 * 로테이션 풀 — hero 4문장 + 같은 톤의 확장.
 *
 * 타입이 **비어 있지 않은 튜플**인 것은 의도다(`noUncheckedIndexedAccess`) — 첫 문장이 항상
 * 존재한다는 걸 타입이 알아야 폴백에 `!` 나 `""` 를 끼워 넣지 않는다.
 */
export const WAITING_SCENE_LINES: readonly [string, ...string[]] = [
  ...HERO_SCENE_LINES,
  "주장들이 심판과 인사를 나누고 있습니다",
  "골키퍼가 골대 앞 잔디를 발로 고르고 있습니다",
  "선수들이 가볍게 몸을 풀고 있습니다",
  "관중석에서 응원가가 울려 퍼지고 있습니다",
  "선심이 깃발을 손에 고쳐 쥐고 있습니다",
  "볼보이가 공을 나르고 있습니다",
  "코치가 화이트보드 앞에서 손짓을 하고 있습니다",
  "선수들이 서로 어깨를 두드리고 있습니다",
  "골키퍼가 그물을 손으로 당겨 보고 있습니다",
  "선수들이 스트레칭으로 다리를 늘이고 있습니다",
  "주심이 공의 바람을 확인하고 있습니다",
  "중계 카메라가 그라운드를 천천히 훑고 있습니다",
  "벤치에서 물병이 오가고 있습니다",
  "조명이 그라운드를 환하게 비추고 있습니다",
];

/**
 * 한 문장이 머무는 시간(초).
 *
 * 1~2초면 읽는 중에 갈리고, 10초면 짧은 대기(실측 6~14초)에서 한 문장만 보고 끝난다.
 * 4초 = 한 문장을 읽고 한 박자 쉬는 길이.
 */
export const WAITING_SCENE_ROTATE_SEC = 4;

/**
 * 경과 초 → 그 시점에 보여줄 정경 문장.
 *
 * **경과 시간에서 파생한다** — 별도 타이머를 두지 않으므로 패널의 경과 시계와 어긋날 수 없고,
 * 순수 함수라 계약이 시간을 흘려보내지 않고도 로테이션 전체를 태울 수 있다.
 * 화면이 비는 경로를 만들지 않으려고 이상한 입력(NaN·음수·무한)은 첫 문장으로 접는다.
 */
export function waitingSceneAt(elapsedSec: number): string {
  const sec = Number.isFinite(elapsedSec) && elapsedSec > 0 ? Math.floor(elapsedSec) : 0;
  const index = Math.floor(sec / WAITING_SCENE_ROTATE_SEC) % WAITING_SCENE_LINES.length;
  return WAITING_SCENE_LINES[index] ?? WAITING_SCENE_LINES[0];
}
